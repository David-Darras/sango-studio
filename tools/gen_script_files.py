"""Writes module/script/src/files.rs: the script files of the game (the archive 29) with the numbers of the scripts that each one holds.

The table comes from the project of the game: the ranges of the numbers of scripts (`scr_offset.cdat` and `scr_offset_id.h`) and the order
of the files in the archive. The descriptions are in `tools/script_file_notes.txt` (one line `first number|description`).

  python tools/gen_script_files.py <folder of the project of the game>
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "module", "script", "src", "files.rs")


def read(path):
    return open(path, "rb").read().decode("cp932", errors="replace")


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
    ids = {}
    for line in read(os.path.join(root, "prog", "include", "assets", "field", "script", "scr_offset_id.h")).split("\n"):
        m = re.match(r"#define\s+(\w+)\s+\((\d+)\)", line)
        if m:
            ids[m.group(1)] = int(m.group(2))
    gaix = {}
    for m in re.finditer(r"GARC_field_script_(\w+)_AMX\s*=\s*(\d+)", read(os.path.join(root, "arc", "field_script.gaix"))):
        gaix[m.group(1)] = int(m.group(2))
    table = read(os.path.join(root, "prog", "include", "assets", "field", "script", "scr_offset.cdat"))
    table = re.sub(r"#if PM_DEBUG.*?#endif\s*//PM_DEBUG", "", table, flags=re.S)
    notes = {}
    for line in open(os.path.join(HERE, "script_file_notes.txt"), encoding="utf-8"):
        if "|" in line:
            key, text = line.rstrip("\n").split("|", 1)
            notes[int(key)] = text
    rows = []
    for m in re.finditer(r"\{\s*//[^\n]*\n\s*(\w+),[^\n]*\n\s*(\w+),[^\n]*\n\s*GARC_field_script_(\w+)_AMX", table):
        start, end, name = ids[m.group(1)], ids[m.group(2)], m.group(3)
        rows.append((gaix[name], name, start, end, notes.get(start, "")))
    rows.sort(key=lambda r: r[2])
    out = ["//! The script files of the game (the archive 29) and the numbers of the scripts that each one holds.\n//!\n//! Generated by `tools/gen_script_files.py`. Do not edit by hand.\n\n"]
    out.append("/// A script file: its place in the archive, the first and the last number of its scripts, and what it is for.\n#[derive(Clone, Copy, Debug)]\npub struct ScriptFile {\n    pub index: usize,\n    pub first: u32,\n    pub last: u32,\n    pub help: &'static str,\n}\n\n")
    out.append("pub const FILES: &[ScriptFile] = &[\n")
    for index, name, start, end, help in rows:
        out.append('    ScriptFile { index: %d, first: %d, last: %d, help: "%s" },\n' % (index, start, end, help.replace('"', '\\"')))
    out.append("];\n")
    open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out))
    print(len(rows), "files")


main()
