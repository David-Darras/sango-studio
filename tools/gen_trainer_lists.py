"""Writes module/trainer/src/lists.rs: the lists that the Trainer page shows instead of raw numbers.

The lists come from the plugin (ORAS part of each header):
  - the animations of the start of the battle: lib/include/battle/constant/encounter_animation.h
  - the 3D models of the trainers:             lib/include/battle/constant/trainer_model.h
  - the background music:                      lib/include/system/constant/background_music.h

  python tools/gen_trainer_lists.py <path of the plugin repository>

The path can also come from the environment variable SANGO_PLUGIN.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "module", "trainer", "src", "lists.rs")

WORDS = {"Wcs": "WCS", "Xy": "XY", "Bgm": "BGM", "Ko": "KO", "Hq": "HQ"}


def humanize(name):
    """kRoute101 -> Route 101, kVsTrainer -> Vs Trainer."""
    name = name[1:] if name.startswith("k") else name
    parts = re.findall(r"[A-Z][a-z]+|[A-Z]+(?![a-z])|\d+", name)
    return " ".join(WORDS.get(p, p) for p in parts)


def entries(path, oras_only):
    text = open(path, encoding="utf-8").read()
    if oras_only:
        # The ORAS part follows "#else" and ends at "#endif".
        text = text.split("#else", 1)[1].split("#endif", 1)[0]
    found = []
    seen = set()
    for name, value in re.findall(r"\b(k[A-Za-z0-9]+)\s*=\s*(\d+)\s*,", text):
        if name in ("kCount", "kDefault") or int(value) in seen:
            continue
        seen.add(int(value))
        found.append((int(value), humanize(name)))
    return sorted(found)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SANGO_PLUGIN")
    if not root:
        sys.exit(__doc__)
    include = os.path.join(root, "lib", "include")
    animations = entries(os.path.join(include, "battle", "constant", "encounter_animation.h"), True)
    models = entries(os.path.join(include, "battle", "constant", "trainer_model.h"), True)
    music = entries(os.path.join(include, "system", "constant", "background_music.h"), True)
    out = ["//! The lists of the Trainer page: the animations of the start of the battle, the 3D models of the trainers and the music.\n//!\n//! Generated by `tools/gen_trainer_lists.py` from the plugin. Do not edit by hand.\n\n"]
    for const, kind, items in [("BATTLE_EFFECTS", "u8", animations), ("MODELS_3D", "u8", models), ("MUSIC", "u16", music)]:
        out.append("pub const %s: [(%s, &str); %d] = [\n" % (const, kind, len(items)))
        for value, name in items:
            out.append('    (%d, "%s"),\n' % (value, name))
        out.append("];\n\n")
    open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out).rstrip("\n") + "\n")
    print(len(animations), len(models), len(music))


main()
