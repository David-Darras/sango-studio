"""Writes module/script/src/opcodes.rs: the instructions of the compiled scripts (the Pawn virtual machine).

The list comes from the Pawn compiler that the game scripts are built with (the file `compiler/sc6.c`: the number, the name and the form of
each instruction):

  python tools/gen_script_opcodes.py <path of sc6.c>

The form of an instruction says how many cells follow it, and which ones are addresses of the code.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "module", "script", "src", "opcodes.rs")

FORMS = {
    "parm0": "Form::Cells(0)", "parm1": "Form::Cells(1)", "parm2": "Form::Cells(2)", "parm3": "Form::Cells(3)", "parm4": "Form::Cells(4)", "parm5": "Form::Cells(5)",
    "parm1_p": "Form::Packed", "do_jump": "Form::Jump", "do_call": "Form::Jump", "do_switch": "Form::Jump",
}


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__)
    text = open(path, encoding="utf-8", errors="replace").read()
    start = text.index("static OPCODE opcodelist[] = {")
    body = text[start:text.index("};", start)]
    found = {}
    for line in body.split("\n"):
        line = line.strip()
        if line.startswith("/*{") or not line.startswith("{"):
            continue
        m = re.match(r'\{\s*(\d+),\s*"([\w.]+)",\s*\w+,\s*(\w+)\s*\}', line)
        if not m:
            continue
        number, name, handler = int(m.group(1)), m.group(2), m.group(3)
        if number == 0 or handler not in FORMS:
            continue
        found[number] = (name, FORMS[handler])
    # the instructions that have a table of values after them
    found[130] = ("casetbl", "Form::CaseTable")
    found[161] = ("icasetbl", "Form::CaseTable")
    out = ["//! The instructions of the compiled scripts.\n//!\n//! Generated by `tools/gen_script_opcodes.py`. Do not edit by hand.\n\n"]
    out.append("/// What follows the number of an instruction.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Form {\n    /// A number of cells.\n    Cells(usize),\n    /// A value packed in the upper half of the first cell.\n    Packed,\n    /// A cell that is an address of the code, counted from the instruction.\n    Jump,\n    /// A number of records, an address for the other cases, then a value and an address for each record.\n    CaseTable,\n}\n\n")
    out.append("/// The instructions: the number, the name and the form.\npub const OPCODES: &[(u32, &str, Form)] = &[\n")
    for number in sorted(found):
        name, form = found[number]
        out.append('    (%d, "%s", %s),\n' % (number, name, form))
    out.append("];\n")
    open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out))
    print(len(found), "instructions")


main()
