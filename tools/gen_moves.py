"""Writes module/species/src/move_names.rs: the name of each move.

The table comes from the plugin: lib/include/pokemon/constant/move.h has the enum MoveId.
The name of an enum value has no spaces, hyphens or apostrophes, so the tool splits it into words
and then fixes the names that the games write differently (see FIXES).
The first name of the list is the move 1.

  python tools/gen_moves.py <path of the plugin repository>

The path can also come from the environment variable SANGO_PLUGIN.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SOURCE = os.path.join("lib", "include", "pokemon", "constant", "move.h")
OUT = os.path.join(REPO, "module", "species", "src", "move_names.rs")

# The names that the split gives wrongly: the name as written by the split, and the name of the games.
FIXES = {
    "Double Edge": "Double-Edge",
    "Self Destruct": "Self-Destruct",
    "Mud Slap": "Mud-Slap",
    "Will O Wisp": "Will-O-Wisp",
    "Uturn": "U-turn",
    "U Turn": "U-turn",
    "X Scissor": "X-Scissor",
    "Freeze Dry": "Freeze-Dry",
    "Trick Or Treat": "Trick-or-Treat",
    "Kings Shield": "King's Shield",
    "Baby Doll Eyes": "Baby-Doll Eyes",
    "Lands Wrath": "Land's Wrath",
    "Forests Curse": "Forest's Curse",
    "Lock On": "Lock-On",
    "Soft Boiled": "Soft-Boiled",
    "Wake Up Slap": "Wake-Up Slap",
    "Topsy Turvy": "Topsy-Turvy",
    "Power Up Punch": "Power-Up Punch",
    "Vcreate": "V-create",
    "V Create": "V-create",
    "Light Of Ruin": "Light of Ruin",
    "Roar Of Time": "Roar of Time",
}


def plugin_path():
    """The path of the plugin repository, from the command line or the environment."""
    if len(sys.argv) > 1:
        return sys.argv[1]
    path = os.environ.get("SANGO_PLUGIN")
    if path:
        return path
    sys.exit("Give the path of the plugin repository: python tools/gen_moves.py <path>")


def words(name):
    """Splits an enum name into words: "KarateChop" gives "Karate Chop"."""
    return " ".join(re.findall(r"[A-Z][a-z]+|[A-Z]+(?![a-z])|\d+|[a-z]+", name))


def read_moves(path):
    """Returns {value: name} for the moves 1 and above, in the version of Alpha Sapphire."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    start = text.index("enum class MoveId")
    body = text[text.index("{", start) + 1:text.index("};", start)]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    moves = {}
    for name, value in re.findall(r"\bk(\w+)\s*=\s*(\d+)", body):
        value = int(value)
        if name in ("None", "Count", "Xxx") or value == 0 or value >= 1000:
            continue
        moves.setdefault(value, FIXES.get(words(name), words(name)))
    return moves


def main():
    moves = read_moves(os.path.join(plugin_path(), SOURCE))
    count = max(moves)
    missing = [n for n in range(1, count + 1) if n not in moves]
    if missing:
        sys.exit("The moves %s have no name." % missing)
    lines = [
        "//! The names of the moves. The move 1 is the first name.",
        "//!",
        "//! Generated by `tools/gen_moves.py` from the move ids of the plugin. Do not edit by hand.",
        "",
        "pub const MOVE: [&str; %d] = [" % count,
    ]
    lines += ['    "%s",' % moves[n] for n in range(1, count + 1)]
    lines.append("];")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %d names in %s" % (count, OUT))


if __name__ == "__main__":
    main()
