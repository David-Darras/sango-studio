"""Writes module/choreography/src/schema.rs: what the Choreography page needs to read and write the choreography files of the moves.

The data comes from the private tools of the plugin (the schema of the steps, the sizes, the names of the resources) and from the game
archives that they read:

  python tools/gen_choreography_schema.py <path of the plugin repository>

The path can also come from the environment variable SANGO_PLUGIN. It writes:
  - the types of the steps (number, name, size, parameters),
  - the lists of choices (enums),
  - the names of the effects, the 3D models and the overlays,
  - the label of each choreography file of the archive.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "module", "choreography", "src", "schema.rs")


def words(name):
    """RunToWords -> Run To Words."""
    return " ".join(re.findall(r"[A-Z][a-z]+|[A-Z]+(?![a-z])|\d+", name))


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SANGO_PLUGIN")
    if not root:
        sys.exit(__doc__)
    sys.path.insert(0, os.path.join(root, "private", "tools"))
    import choreography_schema as sch
    import choreography_data as data

    kinds = data.load_step_kinds()  # name -> number
    schema = sch.parse_schema()
    by_number = {number: name for name, number in kinds.items()}
    out = ["//! What the Choreography page needs to read and write the choreography files of the moves.\n//!\n//! Generated by `tools/gen_choreography_schema.py`. Do not edit by hand.\n\n"]
    out.append("/// The kind of a parameter of a step.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum ParamKind {\n    Int,\n    Bool,\n    Float,\n    Vec3,\n    /// A text of a fixed size in bytes.\n    Text(usize),\n    /// A choice in the list of that name (see [`ENUMS`]).\n    Choice(&'static str),\n    /// A resource: `effect`, `model` or `layout` (see the lists of names).\n    Asset(&'static str),\n    /// The five keys of a curve (80 bytes).\n    Keys5,\n    /// The six windows of a chain attack (48 bytes).\n    Windows6,\n}\n\n")
    out.append("/// A parameter of a step: its name, its kind and its place in the bytes of the step.\n#[derive(Clone, Copy, Debug)]\npub struct Param {\n    pub name: &'static str,\n    pub kind: ParamKind,\n    pub offset: usize,\n    pub size: usize,\n}\n\n")
    out.append("/// A type of step.\n#[derive(Clone, Copy, Debug)]\npub struct StepKind {\n    pub number: u16,\n    pub name: &'static str,\n    /// The size of the parameters, in bytes.\n    pub size: usize,\n    pub params: &'static [Param],\n}\n\n")

    # the sizes and the kinds
    out.append("/// The size of the parameters of each type of step, by number of type.\npub const STEP_SIZES: [u8; %d] = [%s];\n\n" % (len(data.STEP_SIZES), ", ".join(str(s) for s in data.STEP_SIZES)))

    def asset_kind(ptype):
        return sch.ASSET_TYPES[ptype]

    out.append("/// The types of steps, sorted by number.\npub const KINDS: &[StepKind] = &[\n")
    for number in sorted(by_number):
        name = by_number[number]
        params = schema.get(name)
        size = data.STEP_SIZES[number] if number < len(data.STEP_SIZES) else 0
        listed = []
        offset = 0
        for pname, ptype in params or []:
            psize = data.param_size(ptype)
            if ptype == "int":
                kind = "ParamKind::Int"
            elif ptype == "bool":
                kind = "ParamKind::Bool"
            elif ptype == "float":
                kind = "ParamKind::Float"
            elif ptype == "vec":
                kind = "ParamKind::Vec3"
            elif ptype.startswith("str"):
                kind = "ParamKind::Text(%s)" % ptype[3:]
            elif ptype in sch.ENUMS:
                kind = 'ParamKind::Choice("%s")' % ptype
            elif ptype in sch.ASSET_TYPES:
                kind = 'ParamKind::Asset("%s")' % asset_kind(ptype)
            elif ptype == "keys5":
                kind = "ParamKind::Keys5"
            elif ptype == "windows6":
                kind = "ParamKind::Windows6"
            else:
                raise SystemExit("unknown type " + ptype)
            listed.append('Param { name: "%s", kind: %s, offset: %d, size: %d }' % (pname, kind, offset, psize))
            offset += psize
        if params is not None and offset != size:
            raise SystemExit("%s: %d bytes in the schema, %d in the table" % (name, offset, size))
        out.append('    StepKind { number: %d, name: "%s", size: %d, params: &[%s] },\n' % (number, words(name.lstrip("k")), size, ", ".join(listed)))
    out.append("];\n\n")

    out.append("/// The lists of choices: the name of the list, then the name and the number of each choice.\npub const ENUMS: &[(&str, &[(&str, i32)])] = &[\n")
    for name, items in sch.ENUMS.items():
        out.append('    ("%s", &[%s]),\n' % (name, ", ".join('("%s", %d)' % (words(item), value) for item, value in items)))
    out.append("];\n\n")

    # the names of the resources
    files = data.load_sequence_files()
    file_names = data.load_file_names()
    moves = data.load_moves()
    usage = data.collect_assets(files, file_names, moves, kinds)
    names = data.name_assets(usage, moves)
    for asset, const in [("EffectId", "EFFECT_NAMES"), ("EffectModelId", "MODEL_NAMES"), ("OverlayLayoutId", "LAYOUT_NAMES")]:
        items = sorted((value, name) for (a, value), name in names.items() if a == asset)
        out.append("/// The names of the resources of a kind (`%s`): the number, then the name.\npub const %s: &[(i32, &str)] = &[\n" % (asset, const))
        for value, name in items:
            out.append('    (%d, "%s"),\n' % (value, words(name[1:])))
        out.append("];\n\n")

    # the label of each file
    out.append("/// The label of each choreography file of the archive: a move (by its name), or the family of the file and its place.\npub const FILE_LABELS: [&str; %d] = [\n" % len(files))
    for index in range(len(files)):
        owner = data.owner_of(index, file_names, moves)
        out.append('    "%s",\n' % words(owner[0].lstrip("k")) if owner[0] != "NoMove" else '    "No move",\n')
    out.append("];\n")
    open(OUT, "w", encoding="utf-8", newline="\n").write("".join(out))
    print(len(kinds), "kinds,", len(files), "files")


main()
