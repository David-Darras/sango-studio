"""Writes module/music/src/ids.rs and module/music/src/names.rs.

Usage: python gen_music_ids.py <list of the sound ids of the game> <sound archive> <background music header of the plugin> <output folder>

- `ids.rs`: for each music, jingle and sound effect, the place of the sound in the sound archive and its id (the group in the high 16 bits, the
  number in the group in the low 16 bits). Only numbers are written: the labels of the sounds are not kept.
- `names.rs`: the English name of each music, from the names of the plugin (`BackgroundMusicId`).

The list of the sound ids is a text file with lines like `<label> = <number>,`. A label is matched with the name of a sound of the archive.
"""
import re
import struct
import sys

ids_file, archive_file, header_file, out_dir = sys.argv[1:5]

# ---- the sounds of the archive: place, name, kind ----
d = open(archive_file, "rb").read()
u32 = lambda o: struct.unpack_from("<I", d, o)[0]
s32 = lambda o: struct.unpack_from("<i", d, o)[0]
u16 = lambda o: struct.unpack_from("<H", d, o)[0]
blocks = {}
for i in range(3):
    t, _, off, size = struct.unpack_from("<HHII", d, 0x14 + i * 12)
    blocks[t] = off
body = blocks[0x2000] + 8
table = body + u32(body + 4)
names = []
for i in range(u32(table)):
    _, _, off, size = struct.unpack_from("<HHII", d, table + 4 + i * 12)
    names.append(d[table + off:table + off + size].split(b"\0")[0].decode("latin1"))
info = blocks[0x2001] + 8
sound_table = next(info + u32(info + i * 8 + 4) for i in range(8) if u16(info + i * 8) == 0x2100)
sounds = []
for i in range(u32(sound_table)):
    at = sound_table + s32(sound_table + 4 + i * 8 + 4)
    kind = u16(at + 12)
    flags = u32(at + 20)
    name = names[u32(at + 24)] if flags & 1 else ""
    sounds.append((i, name, kind))

# ---- the ids ----
text = open(ids_file, encoding="cp932", errors="ignore").read()
by_label = {label: int(value) for label, value in re.findall(r"^\s*(\w+)\s*=\s*(\d+),", text, re.M)}
streams = [(i, by_label[n]) for i, n, k in sounds if k == 0x2201 and n in by_label]
sequences = [(i, by_label[n]) for i, n, k in sounds if k == 0x2203 and n in by_label]
# The sound effects are the groups of sequences with many sounds (the other groups of sequences are a few musics and the voices).
count = {}
for _, v in sequences:
    count[v >> 16] = count.get(v >> 16, 0) + 1
effects = [(i, v) for i, v in sequences if count[v >> 16] > 50]

lines = [
    "//! The ids of the musics, the jingles and the sound effects of the game.",
    "//!",
    "//! Each line is the place of a sound in the sound archive and its id: the group in the high 16 bits and the number in the group in the",
    "//! low 16 bits. The group 1 is the musics, the group 5 the jingles, the other groups the sound effects. The number of a music is the one",
    "//! that the scripts and the plugin use (for example 1 is the evolution music). Generated by `tools/gen_music_ids.py`: do not change it by hand.",
    "",
    "/// The group of the musics.",
    "pub const GROUP_MUSIC: u32 = 1;",
    "/// The group of the jingles.",
    "pub const GROUP_JINGLE: u32 = 5;",
    "/// The group of the first bank of the sound effects: the one that the sound functions of the plugin use.",
    "pub const GROUP_EFFECT: u32 = 6;",
    "",
    "/// The place of each stream sound in the sound archive and its id.",
    f"pub const STREAMS: [(u16, u32); {len(streams)}] = [",
]
lines += [f"    ({i}, {v})," for i, v in streams]
lines += ["];", "", "/// The place of each sound effect in the sound archive and its id.", f"pub const EFFECTS: [(u16, u32); {len(effects)}] = ["]
lines += [f"    ({i}, {v})," for i, v in effects]
lines += ["];", ""]
open(out_dir + "/ids.rs", "w", encoding="utf-8").write("\n".join(lines))
print(len(streams), "streams,", len(effects), "effects")

# ---- the names of the musics, from the plugin ----
header = open(header_file, encoding="utf-8").read()
music = {}
for name, number in re.findall(r"^\s*k([A-Za-z0-9]+)\s*=\s*(\d+),", header, re.M):
    music.setdefault(int(number), name)  # the first name of a number is the main one

SPECIAL = {
    "Default": "Title Theme", "PokemonTheme": "Title Theme", "Silence": "Silence", "Gts": "Global Trade Station", "Namcave": "Pokemon Link Cave",
    "Theme01": "Theme 1", "Theme02": "Theme 2", "Soaring": "Soaring", "Sky": "Sky", "Sky2": "Sky 2", "Looker02": "Looker 2",
}
WORDS = {"Vs": "Battle:", "Sg": "(ORAS)", "Kw": "Pokemon-Amie"}


def english(name):
    if name in SPECIAL:
        return SPECIAL[name]
    parts = re.findall(r"[A-Z][a-z]+|\d+", name)
    out = []
    for part in parts:
        out.append(WORDS.get(part, part))
    text = " ".join(out)
    for small in ("Of", "The", "In", "On", "And", "To"):
        text = re.sub(rf"(?<=\w) {small}(?= )", f" {small.lower()}", text)
    text = text.replace("Battle: Battle ", "Battle: ")
    text = re.sub(r"Route (\d+)(\d)$", lambda m: f"Route {m.group(1)}{m.group(2)}", text)
    text = text.replace("Pokemon", "Pokémon").replace("Mt ", "Mt. ")
    return text


top = max(music) if music else 0
rows = []
for n in range(top + 1):
    rows.append(english(music[n]) if n in music else "")
lines = [
    "//! The English name of each music, by its number (the number that the scripts and the plugin use).",
    "//!",
    "//! Generated by `tools/gen_music_ids.py` from the names of the plugin: do not change it by hand.",
    "",
    "/// The name of the music with this number, when it has one.",
    f"pub const MUSIC_NAMES: [&str; {len(rows)}] = [",
]
lines += [f'    "{r}",' for r in rows]
lines += ["];", ""]
open(out_dir + "/names.rs", "w", encoding="utf-8").write("\n".join(lines))
print(len(rows), "music names")
